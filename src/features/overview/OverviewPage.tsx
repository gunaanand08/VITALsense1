import { useEffect, useState } from 'react';
import { Link } from 'react-router-dom';
import {
  Activity,
  Cable,
  CircleStop,
  HeartPulse,
  Info,
  Play,
  RotateCcw,
  ShieldAlert,
  TriangleAlert,
} from 'lucide-react';
import { EcgCanvas } from '../../components/ecg/EcgCanvas';
import { Badge, Button, Panel, PanelHeader, Stat, StatusDot, type Tone } from '../../components/ui/primitives';
import { SegmentedControl } from '../../components/ui/controls';
import { ecgEngine } from '../../engine/ecgEngine';
import { useReducedMotion } from '../../hooks/useReducedMotion';
import { useAppStore } from '../../state/store';
import { HeartScene } from '../../three/HeartScene';
import type { BeatEvent } from '../../types/ecg';
import { clamp, formatBpm, formatClock, formatNumber } from '../../utils/format';
import { deriveMonitoring } from './heartState';

function qualityTone(category: string): Tone {
  if (category === 'good') return 'good';
  if (category === 'fair' || category === 'poor') return 'warn';
  return 'danger';
}

function RecentBeats() {
  const [beats, setBeats] = useState<BeatEvent[]>([]);

  useEffect(
    () =>
      ecgEngine.subscribeBeats((beat) => {
        setBeats((previous) => [...previous.slice(-6), beat]);
      }),
    [],
  );

  if (beats.length === 0) {
    return <p className="px-3 py-4 text-[11px] text-text-dim">No beats detected yet.</p>;
  }

  return (
    <ul className="divide-y divide-border">
      {beats
        .slice()
        .reverse()
        .map((beat, index) => (
          <li key={`${beat.index}-${index}`} className="flex items-center justify-between px-3 py-1.5">
            <span className="font-mono text-[11px] tnum text-text-muted">#{beat.index}</span>
            <span className="font-mono text-[12px] tnum text-text">
              {beat.rrMs === null ? '—' : `${beat.rrMs.toFixed(0)} ms`}
            </span>
            <Badge tone={beat.valid ? 'good' : 'warn'}>{beat.valid ? 'valid' : 'artifact'}</Badge>
          </li>
        ))}
    </ul>
  );
}

export function OverviewPage() {
  const telemetry = useAppStore((state) => state.telemetry);
  const mode = useAppStore((state) => state.mode);
  const settings = useAppStore((state) => state.settings);
  const recording = useAppStore((state) => state.recording);
  const busy = useAppStore((state) => state.busy);
  const setMode = useAppStore((state) => state.setMode);
  const startSession = useAppStore((state) => state.startSession);
  const stopSession = useAppStore((state) => state.stopSession);
  const reconnect = useAppStore((state) => state.reconnect);
  const reducedMotionPref = useReducedMotion();
  const reducedMotion = reducedMotionPref || !settings.heart3d;

  const assessment = deriveMonitoring(telemetry, reducedMotion);
  const { heartRate, hrv, quality, connection } = telemetry;
  const sourceIsSimulation = telemetry.sourceKind === 'simulation';
  const stale = telemetry.sampleAgeMs > 2000;

  const tone: Tone =
    assessment.state === 'good'
      ? 'good'
      : assessment.state === 'warning'
        ? 'warn'
        : assessment.state === 'review'
          ? 'danger'
          : assessment.state === 'waiting'
            ? 'idle'
            : 'neutral';

  return (
    <div className="space-y-6">
      <div className="flex flex-col gap-3 lg:flex-row lg:items-end lg:justify-between">
        <div>
          <div className="flex items-center gap-2">
            <h1 className="display text-[30px]">Overview</h1>
            <Badge tone={sourceIsSimulation ? 'idle' : 'accent'} dot>
              {sourceIsSimulation ? 'Simulation mode' : 'Hardware mode'}
            </Badge>
          </div>
          <p className="mt-1.5 max-w-2xl text-[12px] text-text-muted">
            Live single-lead ECG with R-peak detection. {sourceIsSimulation
              ? 'Every value on this screen is generated by the simulator, not measured from a person.'
              : `Streaming from ${connection.deviceId ?? 'an unpaired device'} through the local bridge.`}
          </p>
        </div>

        <div className="flex flex-wrap items-center gap-2">
          <SegmentedControl
            label="Data source"
            value={mode}
            onChange={(next) => void setMode(next)}
            options={[
              { value: 'simulation', label: 'Simulation' },
              { value: 'hardware', label: 'Hardware' },
            ]}
          />
          {mode === 'hardware' && (
            <Button size="sm" icon={<RotateCcw size={13} aria-hidden />} onClick={() => void reconnect()} disabled={busy}>
              Reconnect
            </Button>
          )}
          {recording ? (
            <Button variant="danger" size="sm" icon={<CircleStop size={13} aria-hidden />} onClick={() => void stopSession()} disabled={busy}>
              Stop &amp; save
            </Button>
          ) : (
            <Button variant="primary" size="sm" icon={<Play size={13} aria-hidden />} onClick={startSession} disabled={busy}>
              Start session
            </Button>
          )}
        </div>
      </div>

      <div className="grid gap-6 xl:grid-cols-[minmax(0,1fr)_320px]">
        <div className="min-w-0 space-y-6">
          <Panel className="overflow-hidden">
            <div className="relative">
              <div className="absolute left-6 top-6 z-10 flex flex-wrap items-center gap-2">
                <Badge tone={tone} dot>
                  {assessment.headline}
                </Badge>
                {recording && (
                  <Badge tone="danger" dot>
                    Recording
                  </Badge>
                )}
                {stale && <Badge tone="warn">Stale data</Badge>}
              </div>

              <div className="absolute bottom-6 left-6 z-10">
                <span className="label-mono">Heart rate</span>
                <div className="mt-2 flex items-baseline gap-2.5">
                  <span className="font-mono text-[58px] font-normal leading-[0.85] tnum tracking-[-0.01em] text-text">
                    {formatBpm(heartRate.bpm)}
                  </span>
                  <span className="font-mono text-[9px] uppercase tracking-[0.24em] text-text-dim">bpm</span>
                </div>
                <p className="mt-3 max-w-[19rem] font-serif text-[12.5px] leading-relaxed text-text-dim">
                  {assessment.detail}
                </p>
              </div>

              <div className="absolute bottom-6 right-6 z-10 hidden text-right sm:block">
                <p className="label-mono">{sourceIsSimulation ? 'Simulated signal' : 'Measured signal'}</p>
                <p className="mt-1.5 font-mono text-[10px] tracking-[0.16em] text-text-muted">
                  {telemetry.sampleRateHz || 500} HZ · LEAD I
                </p>
              </div>

              {settings.heart3d ? (
                <HeartScene state={assessment.state} reducedMotion={reducedMotion} className="h-[340px] w-full sm:h-[440px]" />
              ) : (
                <div className="flex h-[340px] w-full flex-col items-center justify-center gap-2 sm:h-[440px]">
                  <HeartPulse size={28} className="text-text-dim" aria-hidden />
                  <p className="text-[12px] text-text-muted">3D heart disabled in Settings</p>
                  <Link
                    to="/settings"
                    className="font-mono text-[9px] uppercase tracking-[0.2em] text-accent-soft underline underline-offset-4 hover:text-text"
                  >
                    Re-enable the 3D scene
                  </Link>
                </div>
              )}
            </div>

            <div className="grid grid-cols-2 gap-6 border-t border-border px-6 py-5 sm:grid-cols-4">
              <Stat label="Latest RR" value={heartRate.lastRrMs === null ? '—' : formatNumber(heartRate.lastRrMs, 0)} unit="ms" size="sm" />
              <Stat label="SDNN" value={hrv.sdnnMs === null ? '—' : formatNumber(hrv.sdnnMs, 1)} unit="ms" size="sm" />
              <Stat label="RMSSD" value={hrv.rmssdMs === null ? '—' : formatNumber(hrv.rmssdMs, 1)} unit="ms" size="sm" />
              <Stat label="Quality" value={quality.category === 'none' ? '—' : `${quality.score}`} unit={quality.category === 'none' ? undefined : '/100'} size="sm" tone={qualityTone(quality.category) as Tone} />
            </div>
          </Panel>

          <Panel>
            <PanelHeader
              title="Live ECG"
              subtitle={`${mode === 'hardware' ? 'Hardware' : 'Simulation'} · ${telemetry.sampleRateHz} Hz · ${settings.windowSeconds}s window`}
              icon={<Activity size={14} aria-hidden />}
              actions={
                <>
                  <Badge tone={qualityTone(quality.category) as Tone}>{quality.category === 'none' ? 'no signal' : quality.category}</Badge>
                  <Link
                    to="/ecg"
                    className="font-mono text-[9px] uppercase tracking-[0.2em] text-accent-soft underline underline-offset-4 hover:text-text"
                  >
                    Open analysis
                  </Link>
                </>
              }
            />
            <div className="p-2">
              <EcgCanvas
                mode="filtered"
                windowSeconds={settings.windowSeconds}
                label={`Live filtered ECG, ${settings.windowSeconds} second window. Heart rate ${
                  heartRate.bpm === null ? 'not yet available' : `${Math.round(heartRate.bpm)} beats per minute`
                }. Signal quality ${quality.category}.`}
                height={188}
              />
            </div>
            <div className="flex flex-wrap items-center justify-between gap-2 border-t border-border px-3 py-2">
              <div className="flex items-center gap-1.5">
                <StatusDot tone={tone} pulse={connection.state === 'streaming'} />
                <span className="font-mono text-[11px] text-text-muted">
                  {connection.stats.samples.toLocaleString()} samples · {connection.stats.batches} batches
                </span>
              </div>
              <div className="flex items-center gap-2">
                <span className="text-[10px] uppercase tracking-[0.1em] text-text-dim">Session</span>
                <span className="font-mono text-[12px] tnum text-text">{formatClock(telemetry.elapsedMs)}</span>
              </div>
            </div>
          </Panel>
        </div>

        <div className="space-y-6">
          <Panel>
            <PanelHeader title="Measurements" subtitle="4 Hz telemetry" />
            <div className="grid grid-cols-2 gap-x-3 gap-y-4 p-3">
              <Stat label="Heart rate" value={formatBpm(heartRate.bpm)} unit="bpm" tone="accent" size="lg" />
              <Stat label="Session avg" value={formatBpm(heartRate.meanBpm)} unit="bpm" />
              <Stat label="Minimum" value={formatBpm(heartRate.minBpm)} unit="bpm" />
              <Stat label="Maximum" value={formatBpm(heartRate.maxBpm)} unit="bpm" />
              <Stat
                label="Valid intervals"
                value={hrv.nnCount}
                hint={hrv.nnCount < hrv.required ? `need ${hrv.required} for HRV` : 'HRV available'}
              />
              <Stat label="Beats detected" value={heartRate.beatCount} hint={`${telemetry.artifacts} artifacts`} />
            </div>
          </Panel>

          <Panel>
            <PanelHeader title="Electrodes" subtitle="AD8232 lead-off state" />
            <div className="space-y-2 p-3">
              {[
                { key: 'LA', label: 'Left arm (LO+)', off: quality.leadOffPos },
                { key: 'RA', label: 'Right arm (LO−)', off: quality.leadOffNeg },
              ].map((electrode) => (
                <div key={electrode.key} className="flex items-center justify-between">
                  <span className="text-[12px] text-text-muted">{electrode.label}</span>
                  <Badge tone={electrode.off ? 'danger' : 'good'} dot>
                    {electrode.off ? 'disconnected' : 'connected'}
                  </Badge>
                </div>
              ))}
              <p className="pt-1 text-[10.5px] leading-relaxed text-text-dim">
                {mode === 'hardware'
                  ? 'State read from the module’s LO+ / LO− digital outputs.'
                  : 'Simulated lead-off state — no electrode is attached.'}
              </p>
            </div>
          </Panel>

          <Panel>
            <PanelHeader title="Recent beats" subtitle="Refined R-peak timing" />
            <RecentBeats />
          </Panel>

          <Panel className="border-warn/30 p-3">
            <div className="flex items-start gap-2">
              <ShieldAlert size={14} className="mt-0.5 shrink-0 text-warn" aria-hidden />
              <p className="text-[11px] leading-relaxed text-text-muted">
                Educational prototype. A single AD8232 lead cannot assess heart health or diagnose any condition.
                {sourceIsSimulation && ' All values shown are synthetic.'}
              </p>
            </div>
          </Panel>
        </div>
      </div>

      {connection.error && (
        <Panel className="flex items-start gap-2 border-danger/35 p-3">
          <TriangleAlert size={14} className="mt-0.5 shrink-0 text-danger" aria-hidden />
          <div className="min-w-0">
            <p className="text-[12px] font-normal text-danger">Connection problem</p>
            <p className="mt-0.5 break-words text-[11px] text-text-muted">{connection.error}</p>
            <p className="mt-1 flex items-center gap-1 text-[10.5px] text-text-dim">
              <Cable size={11} aria-hidden /> Check that <span className="font-mono">npm run server</span> is running, then reconnect from Device Settings.
            </p>
          </div>
        </Panel>
      )}

      <Panel className="flex flex-wrap items-center justify-between gap-2 p-3">
        <div className="flex items-center gap-1.5 text-[11px] text-text-dim">
          <Info size={12} aria-hidden />
          Pulse animation is driven by detected R-peaks ({clamp(heartRate.beatCount, 0, 999999)} so far), never by a fixed timer.
        </div>
        <div className="flex items-center gap-1.5">
          <Badge tone="neutral">{connection.state}</Badge>
          <Badge tone="neutral">{reducedMotion ? 'motion reduced' : 'motion on'}</Badge>
        </div>
      </Panel>
    </div>
  );
}
