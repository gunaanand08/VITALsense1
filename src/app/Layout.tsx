import { NavLink, Outlet, useLocation } from 'react-router-dom';

import { ShieldAlert } from 'lucide-react';
import { useAppStore } from '../state/store';
import { formatClock } from '../utils/format';
import { StatusDot, type Tone } from '../components/ui/primitives';
import { ToastViewport } from '../components/ui/overlays';
import { NAV_ITEMS } from './nav';

function connectionTone(state: string): Tone {
  if (state === 'streaming') return 'good';
  if (state === 'connecting' || state === 'waiting') return 'warn';
  if (state === 'error') return 'danger';
  return 'neutral';
}

/**
 * Top bar: wordmark left, tracked monospace nav centred, live state right.
 * No fill, no blur, no border radius — a hairline under the bar is the only
 * separation from the canvas.
 */
function TopBar() {
  const telemetry = useAppStore((state) => state.telemetry);
  const mode = useAppStore((state) => state.mode);
  const tone = connectionTone(telemetry.connection.state);

  return (
    <header className="sticky top-0 z-40 border-b border-border bg-black/95">
      <div className="mx-auto flex h-14 w-full max-w-[1680px] items-center gap-6 px-5 lg:px-8">
        <div className="flex shrink-0 items-baseline gap-3">
          <span className="font-mono text-[11px] uppercase tracking-[0.42em] text-text">CARDIOPULSE</span>
          <span className="hidden font-serif text-[12px] italic leading-none text-text-dim xl:inline">ECG workstation</span>
        </div>

        <nav aria-label="Primary" className="hidden flex-1 justify-center lg:flex">
          <ul className="flex items-stretch gap-5 xl:gap-8">
            {NAV_ITEMS.map((item) => (
              <li key={item.to}>
                <NavLink
                  to={item.to}
                  end={item.to === '/'}
                  title={item.label}
                  className={({ isActive }) =>
                    [
                      'relative flex h-14 items-center font-mono text-[9.5px] uppercase tracking-[0.2em] transition-colors duration-[140ms]',
                      isActive ? 'text-text' : 'text-text-dim hover:text-text-muted',
                    ].join(' ')
                  }
                >
                  {({ isActive }) => (
                    <>
                      {item.shortLabel}
                      {isActive && <span className="absolute inset-x-0 bottom-0 h-px bg-text" />}
                    </>
                  )}
                </NavLink>
              </li>
            ))}
          </ul>
        </nav>

        <div className="ml-auto flex items-center gap-4 md:ml-0">
          <span
            className="hidden font-mono text-[9px] uppercase tracking-[0.2em] text-text-muted lg:inline"
            title={mode === 'hardware' ? 'Streaming from the bridge' : 'Generated by the simulator'}
          >
            {mode === 'hardware' ? 'Hardware' : 'Simulation'}
          </span>
          <span className="flex items-center gap-2">
            <StatusDot tone={tone} pulse={telemetry.connection.state === 'streaming'} />
            <span className="font-mono text-[9px] uppercase tracking-[0.2em] text-text-muted">
              {telemetry.connection.state}
            </span>
          </span>
          <span className="font-mono text-[11px] tracking-[0.08em] tnum text-text" aria-label="Session duration">
            {formatClock(telemetry.elapsedMs)}
          </span>
        </div>
      </div>
    </header>
  );
}

function MobileNav() {
  return (
    <nav
      aria-label="Primary mobile"
      className="fixed bottom-0 left-0 right-0 z-40 border-t border-border bg-black px-1 pb-[env(safe-area-inset-bottom)] pt-1 lg:hidden"
    >
      <ul className="flex items-stretch justify-between">
        {NAV_ITEMS.map((item) => (
          <li key={item.to} className="flex-1">
            <NavLink
              to={item.to}
              end={item.to === '/'}
              className={({ isActive }) =>
                [
                  'relative flex min-h-[46px] flex-col items-center justify-center gap-1 px-1 py-1.5 font-mono text-[8px] uppercase tracking-[0.14em]',
                  isActive ? 'text-text' : 'text-text-dim',
                ].join(' ')
              }
            >
              <item.icon size={14} aria-hidden />
              <span>{item.shortLabel}</span>
            </NavLink>
          </li>
        ))}
      </ul>
    </nav>
  );
}

export function Layout() {
  const telemetry = useAppStore((state) => state.telemetry);
  const location = useLocation();
  const current = NAV_ITEMS.find((item) => item.to === location.pathname) ?? NAV_ITEMS[0];

  return (
    <div className="min-h-dvh pb-16 lg:pb-0">
      <a
        href="#main"
        className="sr-only focus:not-sr-only focus:absolute focus:left-4 focus:top-4 focus:z-50 focus:border focus:border-text focus:bg-black focus:px-4 focus:py-2 focus:font-mono focus:text-[10px] focus:uppercase focus:tracking-[0.2em] focus:text-text"
      >
        Skip to content
      </a>
      <TopBar />
      <main id="main" className="mx-auto w-full max-w-[1680px] px-5 py-8 lg:px-8 lg:py-10">
        <Outlet />
        <footer className="mt-14 border-t border-border pt-6">
          <div className="flex flex-col gap-3 sm:flex-row sm:items-baseline sm:justify-between">
            <span className="flex items-center gap-2 font-serif text-[12.5px] leading-relaxed text-text-dim">
              <ShieldAlert size={11} aria-hidden />
              Educational instrument — not for diagnosis or treatment decisions.
            </span>
            <span className="font-mono text-[9px] uppercase tracking-[0.2em] text-text-dim">
              {current.label} · {telemetry.sampleRateHz || 500} Hz · local storage only
            </span>
          </div>
          <p className="mt-6 select-none text-center font-mono text-[10px] uppercase tracking-[0.52em] text-text-dim/70">
            Cardiopulse
          </p>
        </footer>
      </main>
      <MobileNav />
      <ToastViewport />
    </div>
  );
}
